import { chromium } from 'playwright'
const browser = await chromium.launch({ channel:'chrome', headless:true, args:['--no-proxy-server'] })
const page = await browser.newPage({ viewport:{width:1440,height:1300} })
const errs=[]; page.on('pageerror', e=>errs.push(String(e.message).slice(0,200)))
await page.goto('http://127.0.0.1:8787/?v=32', { waitUntil:'domcontentloaded' })
await page.waitForTimeout(1200)
await page.click('[data-tpl="security"]')
await page.fill('#site','四川-达州-宣汉县网点818003')
await page.fill('#note','接入完成')
await page.evaluate(async () => {
  const blob = await (await fetch('/logo.png')).blob()
  const f = new File([blob], '模板测试.png', { type:'image/png' })
  const dt = new DataTransfer(); dt.items.add(f)
  document.dispatchEvent(new ClipboardEvent('paste', { clipboardData: dt, bubbles:true, cancelable:true }))
})
await page.waitForTimeout(500)
console.log('暂存数:', await page.locator('.stage').count())
console.log('网点值:', await page.inputValue('#site'))
console.log('说明:', await page.inputValue('#note'))
await page.click('#send')
await page.waitForTimeout(2500)
console.log('toast:', await page.locator('#toast').innerText())
console.log('errors:', errs.join(' | ') || 'none')
await browser.close(); process.exit(0)
