import { chromium } from 'playwright'
const browser = await chromium.launch({ channel:'chrome', headless:true, args:['--no-proxy-server'] })
const page = await browser.newPage({ viewport:{width:1440,height:1300} })
await page.goto('http://127.0.0.1:8787/?v=34', { waitUntil:'domcontentloaded' })
await page.waitForTimeout(1000)
await page.click('[data-tpl="erp-system"]')
await page.fill('#note','测试')
await page.evaluate(async () => {
  const b = await (await fetch('/logo.png')).blob()
  const f = new File([b],'x.png',{type:'image/png'})
  const dt = new DataTransfer(); dt.items.add(f)
  document.dispatchEvent(new ClipboardEvent('paste',{clipboardData:dt,bubbles:true,cancelable:true}))
})
await page.waitForTimeout(300)
await page.click('#send'); await page.waitForTimeout(1200)
console.log('ERP 无省区 → toast:', await page.locator('#toast').innerText())
await page.selectOption('#province','四川省区')
await page.click('#send'); await page.waitForTimeout(1200)
console.log('ERP 有省区无电话 → toast:', await page.locator('#toast').innerText())
await browser.close(); process.exit(0)
